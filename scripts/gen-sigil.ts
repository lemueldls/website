import { existsSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const opentype = require("opentype.js");

const ROOT = resolve(import.meta.dirname, "..");

const ASSETS_BASE_URL = process.env.NUXT_ASSETS_BASE_URL ?? "https://assets.lemueldls.dev";

const SOURCE_URL = `${ASSETS_BASE_URL}/fonts/truetype/AsterismText-Regular.ttf`;

const ASTERISM = "⁂"; // ⁂ U+2042

const VIEWBOX = 24;

const PAD = 0.05;

interface LoadedFont {
  unitsPerEm: number;
  charToGlyph: (character: string) => {
    unicode: number;
    advanceWidth: number;
    getPath: (
      x: number,
      y: number,
      fontSize: number,
    ) => {
      getBoundingBox: () => { x1: number; y1: number; x2: number; y2: number };
      toPathData: (precision: number) => string;
    };
  };
}

async function loadFont(): Promise<{ font: LoadedFont; source: string }> {
  const local = [
    process.env.ASTERISM_TTF,
    "/home/lemuel/.nix-profile/share/fonts/truetype/AsterismText-Regular.ttf",
    "/nix/store/g0k4msv1p8h2xnvh3s773bmsgnvqyhsr-home-manager-path/share/fonts/truetype/AsterismText-Regular.ttf",
  ]
    .filter((p): p is string => Boolean(p))
    .find((p) => existsSync(p));

  if (local) {
    return { font: opentype.loadSync(local), source: local };
  }

  const res = await fetch(SOURCE_URL);
  if (!res.ok) {
    console.error(
      `[gen:sigil] ${SOURCE_URL} returned ${res.status}. ` +
        `Set ASTERISM_TTF to cut from a local face instead.`,
    );
    process.exit(1);
  }

  const buffer = await res.arrayBuffer();
  return { font: opentype.parse(buffer), source: SOURCE_URL };
}

const { font, source } = await loadFont();

const glyph = font.charToGlyph(ASTERISM);

if (!glyph || glyph.unicode !== 0x2042) {
  console.error(`[gen:sigil] ${source} has no glyph for U+2042.`);
  process.exit(1);
}

const outline = glyph.getPath(0, 0, font.unitsPerEm);
const box = outline.getBoundingBox();

if (box.x2 - box.x1 < 1 || box.y2 - box.y1 < 1) {
  console.error("[gen:sigil] empty glyph outline.");
  process.exit(1);
}

const inkWidth = box.x2 - box.x1;
const inkHeight = box.y2 - box.y1;
const drawable = VIEWBOX * (1 - PAD * 2);

const scale = Math.min(drawable / inkWidth, drawable / inkHeight);

const tx = VIEWBOX / 2 - ((box.x1 + box.x2) / 2) * scale;
const ty = VIEWBOX / 2 - ((box.y1 + box.y2) / 2) * scale;

const transform = `translate(${tx.toFixed(3)} ${ty.toFixed(3)}) scale(${scale.toFixed(5)})`;
const data = outline.toPathData(2);

const svg = (fill: string) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${VIEWBOX} ${VIEWBOX}" width="${VIEWBOX}" height="${VIEWBOX}">\n` +
  `  <g fill="${fill}"><path d="${data}" transform="${transform}"/></g>\n` +
  `</svg>\n`;

await mkdir(resolve(ROOT, "public"), { recursive: true });

await writeFile(resolve(ROOT, "public/icon.svg"), svg("#00a896"), "utf8");
await writeFile(resolve(ROOT, "public/icon-on-light.svg"), svg("#11111b"), "utf8");
await writeFile(resolve(ROOT, "public/icon-on-dark.svg"), svg("#cdd6f4"), "utf8");

await mkdir(resolve(ROOT, "app/lib"), { recursive: true });
await writeFile(
  resolve(ROOT, "app/lib/sigil.ts"),
  [
    "// Generated by scripts/gen-sigil.ts // do not edit by hand.",
    `// Source: ${source}, U+2042, advance ${glyph.advanceWidth}/1000.`,
    `export const SIGIL_PATH = ${JSON.stringify(data)};`,
    "",
    `export const SIGIL_TRANSFORM = ${JSON.stringify(transform)};`,
    "",
    `export const SIGIL_VIEWBOX = "0 0 ${VIEWBOX} ${VIEWBOX}";`,
    "",
  ].join("\n"),
  "utf8",
);

const fromEndpoint = source === SOURCE_URL;
console.log(
  `[gen:sigil] ${fromEndpoint ? "fetched" : "local"} ${source} U+2042 → ${VIEWBOX}px box, ` +
    `ink ${inkWidth.toFixed(0)}×${inkHeight.toFixed(0)} units, scale ${scale.toFixed(4)}` +
    `${fromEndpoint ? "" : " (set ASSETS_BASE_URL to prefer the published build)"}`,
);
